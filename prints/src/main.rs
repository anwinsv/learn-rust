fn main() {
    println!("Hello, world!");

    print!("Print using print! macro");

    println!("Value of 2 + 2 is: {}", 2 + 2);

    println!("Name: {}, Age: {}", "Alice", 30);

    print!("All of this will be printed on the same line");
    print!("This is the second part of the same line");

    print!("This use print macro
    to print without newline
    in different lines");
}